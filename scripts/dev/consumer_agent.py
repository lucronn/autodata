#!/usr/bin/env python3
"""Review the AutoData chat experience from a consumer's point of view.

The runner is intentionally deterministic. It calls only the configured chat
HTTP boundary, records a consumer-visible projection of each answer, scores
the contract dimensions, and optionally creates deduplicated GitHub issues for
reproducible findings.
"""

from __future__ import annotations

import argparse
from copy import deepcopy
from datetime import UTC, datetime
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import time
